import { expect, test } from '@playwright/test'
import { fixture, normalItem, addVtd } from './checkout.fixture'

test('VTA vinculada habilitada, recuperación y cierre pendiente de Almacén', async ({ page }) => {
  const writes = await fixture(page, { openVtd: true })
  await page.goto('/')
  await normalItem(page); await addVtd(page)
  await expect(page.getByRole('region', { name: 'Operación con Almacén' })).toContainText('Puedes agregar productos VTA y cobrar todo junto')
  await expect(page.locator('.grand-total')).toContainText('170,00')
  await expect(page.getByRole('button', { name: 'Nueva operación', exact: true })).toBeDisabled()
  await expect(page.locator('.cart-panel')).toContainText('VTD-2026-0013')
  await page.reload()
  await expect(page.locator('.grand-total')).toContainText('170,00')
  await page.setViewportSize({ width: 1280, height: 720 })
  await expect(page.getByRole('button', { name: /Cobrar todo/ })).toBeInViewport()
  await page.screenshot({ path: '.ui-review.local/caja-almacen-operacion.png', fullPage: true })
  await page.getByRole('button', { name: /Cobrar todo/ }).click()
  await page.getByRole('button', { name: 'Confirmar cobro', exact: true }).click()
  await expect(page.getByRole('heading', { name: '¡Cobro confirmado!' })).toBeVisible()
  await page.getByRole('button', { name: 'Volver a la operación pendiente', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Completar entrega y operación' })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Nueva operación', exact: true })).toBeDisabled()
  await expect(page.locator('.caja-almacen-panel')).toContainText('Cobro registrado')
  expect(writes).toHaveLength(1)
  writes.deliver()
  await page.getByRole('button', { name: 'Actualizar estado de Almacén' }).click()
  await expect(page.getByRole('button', { name: 'Completar entrega y operación' })).toBeEnabled()
  await page.setViewportSize({ width: 1280, height: 720 })
  await page.screenshot({ path: '.ui-review.local/caja-almacen-cobrado-compacto.png', fullPage: true })
  await page.getByRole('button', { name: 'Completar entrega y operación' }).click()
  await expect(page.locator('.caja-almacen-panel')).toHaveCount(0)
  expect(writes).toHaveLength(1)
  expect(writes.runtimeErrors).toEqual([])
})

test('solicitar material conserva la operación y permite añadir VTA antes de cobrar', async ({ page }) => {
  const writes=await fixture(page,{products:true})
  await page.goto('/')
  await page.locator('.cart-operation-menu > summary').click()
  await page.getByRole('button',{name:'Venta directa de almacén',exact:true}).click()
  await page.getByRole('button',{name:'Agregar Material de Almacén QA',exact:true}).click()
  await page.getByRole('button',{name:/Solicitar a Almacén y continuar VTA/}).click()
  await expect(page.locator('.caja-almacen-panel')).toContainText('Continúa esta operación')
  await expect(page.locator('.catalog-chips')).not.toContainText('Material de Almacén QA')
  await normalItem(page)
  await expect(page.locator('.grand-total')).toContainText('170,00')
  expect(writes).toHaveLength(1)
  expect(writes[0].body.p_datos).toMatchObject({solicitud:{ubicacion_id:31,lineas:[{producto_id:44,precio_unitario:150}]},borrador:{cart:[]}})
  expect(writes.runtimeErrors).toEqual([])
})
