import fs from 'node:fs/promises'
import assert from 'node:assert/strict'

export async function testTrazabilidadCobros(db, claims) {
  const admin='00000000-0000-0000-0000-000000000001', caja='00000000-0000-0000-0000-000000000002'
  await claims(admin)
  const control=()=>db.query('select count(*)::int n,sum(monto) suma from hermes.movimiento_cuenta')
  const before=await control()
  await db.exec(await fs.readFile(new URL('../migrations/20261017230621_detalle_partidas_trazabilidad_cobros.sql',import.meta.url),'utf8'))
  assert.deepEqual(await control(),before,'Instalar el historial no altera la cartera')
  assert.equal((await db.query('select count(*)::int n from hermes.cobro_evento')).rows[0].n,1,'No se inventa historial de operaciones anteriores')
  const detail=async(id,cursor=null,limit=50)=>(await db.query('select public.consultar_detalle_cobro_pedido($1,$2,$3) r',[id,cursor,limit])).rows[0].r
  let d=await detail(885001)
  assert.equal(d.resumen.saldadas,2)
  assert.equal(d.resumen.vigentes,2)
  assert(d.partidas.every(p=>p.saldada_en===null),'Las fechas históricas desconocidas permanecen desconocidas')
  assert(d.pagos.every(p=>p.cobrado_por.historico),'La identidad histórica no se presenta como captura nueva')
  const create=async(id)=>{
    await db.query("insert into public.pedido(id,categoria,cliente_id,total,subtotal,numero) values($1,'MAYOR',900001,100,100,$2)",[id,`TRAZA-${id}`])
    return (await db.query('select id from hermes.partida_abierta where pedido_id=$1',[id])).rows[0].id
  }
  const pa=await create(885101)
  await db.query("update public.sesion_caja set estado='ABIERTA',cajero_id=$1 where id=900001",[caja])
  const cashier=(await db.query('select nombre,rol from public.perfil where id=$1',[caja])).rows[0]
  await claims(caja)
  const cobrar=async()=> (await db.query("select public.registrar_cobro_cation(p_pedido_id=>885101,p_cliente_id=>900001,p_monto=>100,p_metodo=>'EFECTIVO',p_sesion_id=>900001,p_idempotencia=>'traza-cobro-1',p_aplicaciones=>$1) r",[JSON.stringify([{partida_id:pa,monto:100}])])).rows[0].r
  const cobro=await cobrar()
  d=await detail(885101)
  assert.equal(d.resumen.saldadas,0)
  assert.equal(Number(d.partidas[0].en_revision),100)
  assert.equal(d.pagos[0].cobrado_por.id,caja)
  assert.equal(d.pagos[0].cobrado_por.rol,'cajero')
  assert.equal(d.pagos[0].turno.responsable.id,caja)
  const n=(await db.query('select count(*)::int n from hermes.cobro_evento')).rows[0].n
  assert.equal((await cobrar()).pagoId,cobro.pagoId)
  assert.equal((await db.query('select count(*)::int n from hermes.cobro_evento')).rows[0].n,n,'El reintento no duplica la auditoría')
  await claims(admin)
  await db.query("select hermes.confirmar_pago($1,'Autor falso desde el cliente')",[cobro.pagoId])
  d=await detail(885101)
  assert.equal(d.resumen.saldadas,1)
  assert.equal(d.partidas[0].fecha_saldado_fuente,'AUDITADA')
  assert(d.partidas[0].saldada_en)
  assert.equal(d.pagos[0].verificado_por.id,admin)
  assert.equal(d.pagos[0].verificado_por.rol,'admin')
  assert.notEqual(d.pagos[0].verificado_por.nombre,'Autor falso desde el cliente')
  const hermes=(await db.query('select hermes.obtener_detalle_cobro_partida($1) r',[pa])).rows[0].r
  assert.deepEqual(hermes.partidas,d.partidas,'Seller y Conciliador usan el mismo detalle')
  assert.deepEqual(hermes.pagos,d.pagos)
  await db.query("update public.perfil set nombre='Nombre cambiado',rol='gerente' where id=$1",[caja])
  d=await detail(885101)
  assert.equal(d.pagos[0].cobrado_por.nombre,cashier.nombre)
  assert.equal(d.pagos[0].cobrado_por.rol,'cajero','El rol histórico no cambia con el perfil')
  assert.equal(d.pagos[0].turno.responsable.rol,'cajero')
  await db.query('update public.perfil set nombre=$1,rol=$2 where id=$3',[cashier.nombre,cashier.rol,caja])
  const first=await detail(885101,null,2)
  assert(first.siguiente)
  const next=await detail(885101,first.siguiente,2)
  assert(next.historial.every(e=>Number(e.id)<Number(first.siguiente)))
  assert(!next.historial.some(e=>first.historial.some(x=>x.id===e.id)))
  await assert.rejects(()=>db.query("update hermes.cobro_evento set accion='FALSO' where id=(select max(id) from hermes.cobro_evento)"),/inmutable/)
  await assert.rejects(()=>db.query('truncate hermes.cobro_evento'),/inmutable/)
  await db.query('delete from hermes.pago_aplicacion where pago_id=$1 and partida_id=$2',[cobro.pagoId,pa])
  d=await detail(885101)
  assert.equal(d.resumen.saldadas,0)
  assert.equal(d.partidas[0].saldada_en,null)
  assert(d.historial.some(e=>e.accion==='PARTIDA_REABIERTA'))
  await db.query('insert into hermes.pago_aplicacion(pago_id,partida_id,monto) values($1,$2,100)',[cobro.pagoId,pa])
  assert.equal((await detail(885101)).resumen.saldadas,1)
  const wallet=await create(885103)
  await db.query("select public.aplicar_saldo_pedido(885103,100,900001,'traza-saldo-1')")
  d=await detail(885103)
  assert.equal(d.resumen.saldadas,1)
  assert.equal(d.saldos.length,1)
  assert.equal(d.saldos[0].aplicado_por.id,admin)
  assert.equal(d.pagos.length,0,'Aplicar saldo existente no inventa un cobro nuevo')
  assert(d.historial.some(e=>e.accion==='PARTIDA_SALDADA'))
  await db.query("select public.anular_pedido_con_cartera(885103,'Reversión de prueba')")
  d=await detail(885103)
  assert.equal(d.resumen.vigentes,0)
  assert(d.saldos[0].anulado_en)
  assert(d.historial.some(e=>e.accion==='SALDO_REVERTIDO'))
  await claims(caja)
  await db.exec('set role authenticated')
  assert.equal((await detail(885101)).resumen.saldadas,1)
  await assert.rejects(()=>db.query("insert into hermes.cobro_evento(accion,entidad,entidad_id,actor) values('FALSO','x',1,'{}')"),/permission denied/)
  await db.exec('reset role')
  await assert.rejects(()=>db.query('select hermes.obtener_detalle_cobro_partida($1)',[pa]),/Hermes/)
  await claims(admin)
  for(const signature of ['hermes.capturar_cobro_evento()','hermes.cobro_actor(text,boolean)','hermes.detalle_cobro_interno(bigint,bigint,bigint,integer)'])
    assert.equal((await db.query("select has_function_privilege('authenticated',$1,'EXECUTE') p",[signature])).rows[0].p,false)
  assert.equal((await db.query("select has_function_privilege('anon','public.consultar_detalle_cobro_pedido(bigint,bigint,integer)','EXECUTE') p")).rows[0].p,false)
  await assert.rejects(()=>detail(885101,null,101),/Paginación/)
  await db.query("select set_config('request.jwt.claims','',false)")
  await assert.rejects(()=>detail(885101),/No autorizado/)
  await claims(admin)
  const destino=await create(885104)
  await db.query('update hermes.pago_aplicacion set partida_id=$1 where pago_id=$2 and partida_id=$3',[destino,cobro.pagoId,pa])
  const origenReasignado=await detail(885101), destinoReasignado=await detail(885104)
  assert(origenReasignado.historial.some(e=>e.accion==='APLICACION_REASIGNADA_DESDE'))
  assert(destinoReasignado.historial.some(e=>e.accion==='APLICACION_MODIFICADA'))
  assert.equal(origenReasignado.resumen.saldadas,0)
  assert.equal(destinoReasignado.resumen.saldadas,1)
  assert(origenReasignado.pagos.some(p=>p.id===cobro.pagoId),'El origen conserva el rastro del pago reasignado')
  await db.query("insert into hermes.partida_abierta(cliente_id,cliente_nombre,cliente_categoria,documento_interno,inicio_computo,pedido_id,total,estado,creado_por,parent_partida_id,partida_raiz_id,entrega_numero) select cliente_id,cliente_nombre,cliente_categoria,'TRAZA-HIJA-PRUEBA',inicio_computo,pedido_id,25,'ABIERTA','Prueba',id,id,2 from hermes.partida_abierta where id=$1",[destino])
  await db.query('update public.pedido set total=125,subtotal=125 where id=885104')
  const contador=(await db.query('select public.consultar_cobros_pedidos(array[885104]::bigint[]) r')).rows[0].r[0]
  assert.equal(contador.partidas_saldadas,1)
  assert.equal(contador.partidas,2)
  assert.equal(contador.estado,'parcial')
  console.log('OK: detalle compartido, fecha auditada sin inventar pasado, cobrador/verificador/turno, rol congelado, aplicaciones, saldo y reversión, inmutabilidad, cursor, reintento y permisos')
}
