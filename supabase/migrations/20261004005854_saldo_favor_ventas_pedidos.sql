-- Pool de orígenes: apertura acreedora y dinero/ajustes confirmados todavía sin consumir.
-- Las contrapartidas de anulación no son fondos nuevos: se libera el origen original.
create function hermes.fuentes_saldo_disponible(p_cliente_id bigint)
returns table(movimiento_id bigint,disponible numeric) language sql stable security definer
set search_path=pg_catalog,hermes,public as $$
 with cargos_previos as (
  select coalesce(sum(m.monto),0) monto from hermes.movimiento_cuenta m
  where m.cliente_id=p_cliente_id and m.monto>0 and m.partida_id is null
  and m.tipo::text in ('SALDO_APERTURA','AJUSTE','CARGO')
  and not exists(select 1 from public.saldo_cliente_uso s where s.movimiento_id=m.id)
 ), fuentes as (
 select m.id,m.fecha_efectiva,greatest(-m.monto-coalesce(u.aplicado,0),0) fondo
 from hermes.movimiento_cuenta m
 left join lateral(select sum(f.monto) aplicado from hermes.saldo_uso_fuente f
   join public.saldo_cliente_uso s on s.id=f.uso_id where f.movimiento_id=m.id and s.anulado_en is null) u on true
 where m.cliente_id=p_cliente_id and m.monto<0 and m.tipo::text in ('SALDO_APERTURA','ANTICIPO','NOTA_CREDITO','AJUSTE')
 and coalesce(m.idempotencia_clave,'') not like 'anulacion-partida-%'
 and not exists(select 1 from public.saldo_cliente_uso s where s.reversion_id=m.id)
 and (m.pago_id is null or exists(select 1 from hermes.pago p where p.id=m.pago_id and p.estado::text in ('CONFIRMADO','ACREDITADO')))
 ), ordenadas as (
  select *,coalesce(sum(fondo) over(order by fecha_efectiva,id rows between unbounded preceding and 1 preceding),0) anterior from fuentes
 )
 select id,greatest(fondo-greatest((select monto from cargos_previos)-anterior,0),0) from ordenadas order by fecha_efectiva,id
$$;
revoke all on function hermes.fuentes_saldo_disponible(bigint) from public,anon,authenticated,service_role;

create function public.consultar_saldo_disponible(p_cliente_id bigint,p_pedido_id bigint default null)
returns jsonb language plpgsql stable security definer set search_path=pg_catalog,public,hermes as $$
declare cid bigint; saldo numeric; fondos numeric; pendiente numeric:=0; revision numeric;
begin
 perform hermes.exigir_operador_pos();
 if not exists(select 1 from public.cliente where id=p_cliente_id and activo and tipo_precio::text in ('mayorista','institucion','corporativo')) then
   return jsonb_build_object('sinCuenta',true,'disponible',0); end if;
 select id into cid from hermes.cliente where pos_cliente_id=p_cliente_id and activo;
 if cid is null then return jsonb_build_object('sinCuenta',true,'disponible',0); end if;
 select saldo_confirmado,monto_en_revision into saldo,revision from hermes.v_saldo_cliente where cliente_id=cid;
 select coalesce(sum(disponible),0) into fondos from hermes.fuentes_saldo_disponible(cid);
 if p_pedido_id is not null then
  if not exists(select 1 from public.pedido where id=p_pedido_id and cliente_id=p_cliente_id and estado::text in ('ABIERTO','COMPLETADO')) then raise exception 'El pedido no pertenece al cliente o está anulado'; end if;
  select coalesce(sum(greatest(ve.pendiente-ve.en_revision,0)),0) into pendiente from hermes.v_partida_estado ve where pedido_id=p_pedido_id and cliente_id=cid and estado::text='ABIERTA';
  fondos:=least(fondos,pendiente);
 else fondos:=least(fondos,greatest(-coalesce(saldo,0),0)); end if;
 return jsonb_build_object('sinCuenta',false,'saldoConfirmado',coalesce(saldo,0),'disponible',fondos,'enRevision',coalesce(revision,0),'pedidoPendiente',pendiente,'aplicadoPedido',(select coalesce(sum(monto),0) from public.saldo_cliente_uso where pedido_id=p_pedido_id and anulado_en is null),'esAcreedor',coalesce(saldo,0)<0);
end $$;
revoke all on function public.consultar_saldo_disponible(bigint,bigint) from public,anon;
grant execute on function public.consultar_saldo_disponible(bigint,bigint) to authenticated;

create function hermes.marcar_venta_acreedora() returns trigger language plpgsql security definer set search_path=pg_catalog,public,hermes as $$
declare cid bigint;
begin
 new.cliente_acreedor:=false;new.saldo_cliente_antes:=null;new.saldo_favor_aplicado:=0;
 if new.cliente_id is not null and exists(select 1 from public.cliente where id=new.cliente_id and activo and tipo_precio::text in ('mayorista','institucion','corporativo')) then
  select id into cid from hermes.cliente where pos_cliente_id=new.cliente_id and activo for update;
  if cid is not null then
   select coalesce(sum(monto),0) into new.saldo_cliente_antes from hermes.movimiento_cuenta where cliente_id=cid;
   new.cliente_acreedor:=new.saldo_cliente_antes<0;
  end if;
 end if;
 return new;
end $$;
revoke all on function hermes.marcar_venta_acreedora() from public,anon,authenticated,service_role;
create trigger saldo_marcar_venta before insert on public.venta for each row execute function hermes.marcar_venta_acreedora();

create function hermes.registrar_uso_saldo() returns trigger language plpgsql security definer set search_path=pg_catalog,public,hermes as $$
declare cid bigint; saldo numeric; fondos numeric; pendiente numeric; restante numeric; tomado numeric; r record; v public.venta%rowtype; s public.sesion_caja%rowtype; actor public.perfil%rowtype;
begin
 perform hermes.exigir_operador_pos();
 select * into actor from public.perfil where id=auth.uid() and activo and rol in ('cajero','admin','gerente');
 if not found then raise exception 'Se requiere un operador activo para usar saldo' using errcode='42501';end if;
 select * into s from public.sesion_caja where id=new.sesion_caja_id for share;
 if not found or s.estado::text<>'ABIERTA' then raise exception 'La caja está cerrada';end if;
 if actor.rol='cajero' and s.cajero_id is distinct from actor.id then raise exception 'Solo puedes operar en tu propio turno' using errcode='42501';end if;
 if new.idempotencia_clave is null or length(btrim(new.idempotencia_clave))<1 or length(new.idempotencia_clave)>200 then raise exception 'Clave de operación inválida';end if;
 if new.monto is null or new.monto<=0 or new.monto::text in ('NaN','Infinity','-Infinity') then raise exception 'Importe de saldo inválido';end if;
 if not exists(select 1 from public.cliente where id=new.cliente_id and activo and tipo_precio::text in ('mayorista','institucion','corporativo')) then raise exception 'El saldo solo aplica a clientes mayoristas, institucionales y corporativos';end if;
 select id into cid from hermes.cliente where pos_cliente_id=new.cliente_id and activo for update;
 if cid is null then raise exception 'El cliente no tiene cuenta activa en el conciliador';end if;
 new.hermes_cliente_id:=cid;new.creado_por_id:=actor.id;new.creado_por:=coalesce(actor.email,actor.id::text);new.creado_en:=now();new.anulado_en:=null;new.motivo_anulacion:=null;new.reversion_id:=null;new.movimiento_id:=null;
 select coalesce(sum(monto),0) into saldo from hermes.movimiento_cuenta where cliente_id=cid;
 new.saldo_antes:=saldo;
 select coalesce(sum(disponible),0) into fondos from hermes.fuentes_saldo_disponible(cid);
 if new.venta_id is not null then
  select * into v from public.venta where id=new.venta_id for update;
  if not found or v.estado::text<>'ABIERTA' or v.cliente_id is distinct from new.cliente_id or v.sesion_caja_id is distinct from new.sesion_caja_id or v.numero not like 'VTA-%' then raise exception 'La venta no admite esta aplicación de saldo';end if;
  fondos:=least(fondos,greatest(-saldo,0));
  if new.monto+coalesce((select sum(monto) from public.venta_pago where venta_id=new.venta_id),0)>v.total then raise exception 'El saldo aplicado supera el pendiente de la venta';end if;
 else
  if not exists(select 1 from public.pedido where id=new.pedido_id and cliente_id=new.cliente_id and estado::text in ('ABIERTO','COMPLETADO')) then raise exception 'Pedido inválido o anulado';end if;
  perform 1 from hermes.partida_abierta where cliente_id=cid order by id for update;
  select coalesce(sum(greatest(ve.pendiente-ve.en_revision,0)),0) into pendiente from hermes.v_partida_estado ve where pedido_id=new.pedido_id and cliente_id=cid and estado::text='ABIERTA';
  if new.monto+coalesce((new.solicitud->>'nuevo')::numeric,0)>pendiente then raise exception 'El saldo y el dinero nuevo superan el pendiente vigente';end if;
  fondos:=least(fondos,pendiente);
 end if;
 if new.monto>fondos then raise exception 'El saldo disponible cambió: puedes aplicar hasta Bs %. Actualiza antes de confirmar.',fondos;end if;
 restante:=new.monto;
 for r in select * from hermes.fuentes_saldo_disponible(cid) loop
  exit when restante<=0;
  tomado:=least(restante,r.disponible);
  if tomado>0 then insert into hermes.saldo_uso_fuente(uso_id,movimiento_id,monto) values(new.id,r.movimiento_id,tomado);restante:=restante-tomado;end if;
 end loop;
 if restante<>0 then raise exception 'No se pudo reservar el saldo confirmado';end if;
 if new.venta_id is not null then
  insert into hermes.movimiento_cuenta(cliente_id,tipo,monto,idempotencia_clave,fecha_efectiva,referencia,motivo,creado_por)
  values(cid,'CARGO',new.monto,'saldo-venta-'||new.venta_id,(now() at time zone 'America/La_Paz')::date,v.numero,'Compra cubierta con saldo a favor',new.creado_por) returning id into new.movimiento_id;
  update public.venta set saldo_favor_aplicado=new.monto,cliente_acreedor=saldo<0,saldo_cliente_antes=saldo where id=new.venta_id;
  new.saldo_despues:=saldo+new.monto;
 else
  restante:=new.monto;
  for r in select ve.partida_id,greatest(ve.pendiente-ve.en_revision,0) disponible from hermes.v_partida_estado ve where pedido_id=new.pedido_id and cliente_id=cid and estado::text='ABIERTA' order by creado_en,partida_id loop
   exit when restante<=0;tomado:=least(restante,r.disponible);
   if tomado>0 then insert into hermes.saldo_uso_partida(uso_id,partida_id,monto) values(new.id,r.partida_id,tomado);restante:=restante-tomado;end if;
  end loop;
  if restante<>0 then raise exception 'El pendiente del pedido cambió';end if;
  -- El cargo del pedido ya redujo el saldo de cuenta. Aplicar no vuelve a descontarlo.
  new.saldo_despues:=saldo;
 end if;
 return new;
end $$;
revoke all on function hermes.registrar_uso_saldo() from public,anon,authenticated,service_role;
create trigger saldo_registrar_uso before insert on public.saldo_cliente_uso for each row execute function hermes.registrar_uso_saldo();

