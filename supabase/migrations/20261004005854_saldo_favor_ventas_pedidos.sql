create function public.registrar_venta_con_saldo(p_lineas jsonb,p_pagos jsonb,p_sesion_caja_id bigint,p_cliente_id bigint,p_saldo_favor numeric,p_descuento_total numeric default 0,p_usuario text default null,p_idempotencia text default null)
returns jsonb language plpgsql set search_path=pg_catalog,public as $$
declare resultado jsonb; v public.venta%rowtype; u public.saldo_cliente_uso%rowtype; pagos jsonb; actor text;
begin
 if auth.uid() is null or not exists(select 1 from public.perfil where id=auth.uid() and activo and rol in ('admin','gerente','cajero')) then raise exception 'Operador no autorizado' using errcode='42501';end if;
 select coalesce(email,id::text) into actor from public.perfil where id=auth.uid();
 if p_saldo_favor is null or p_saldo_favor<=0 or p_saldo_favor::text in ('NaN','Infinity','-Infinity') or p_idempotencia is null or btrim(p_idempotencia)='' or length(p_idempotencia)>200 then raise exception 'Importe o clave de saldo inválidos';end if;
 if p_pagos is null or jsonb_typeof(p_pagos)<>'array' or exists(select 1 from jsonb_array_elements(p_pagos) p where p->>'metodo'='SALDO_FAVOR') then raise exception 'Pagos nuevos inválidos';end if;
 perform pg_advisory_xact_lock(hashtextextended('venta:'||p_idempotencia,0));
 select * into v from public.venta where idempotencia_clave=p_idempotencia;
 if found and (v.cliente_id is distinct from p_cliente_id or v.sesion_caja_id is distinct from p_sesion_caja_id or v.saldo_favor_aplicado<>round(p_saldo_favor,2) or v.estado::text='ANULADA') then raise exception 'La clave corresponde a otra venta o está anulada';end if;
 pagos:=p_pagos||jsonb_build_array(jsonb_build_object('metodo','SALDO_FAVOR','monto',round(p_saldo_favor,2)));
 resultado:=public.registrar_venta(p_lineas,pagos,p_sesion_caja_id,p_cliente_id,p_descuento_total,actor,p_idempotencia);
 select * into u from public.saldo_cliente_uso where venta_id=(resultado->>'venta_id')::bigint;
 if not found then raise exception 'No se pudo verificar el consumo de saldo';end if;
 return resultado||jsonb_build_object('saldo_favor_aplicado',u.monto,'saldo_favor_restante',greatest(-u.saldo_despues,0),'cliente_acreedor',u.saldo_antes<0);
end $$;
