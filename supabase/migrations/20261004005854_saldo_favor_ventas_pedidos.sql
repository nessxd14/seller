create function public.aplicar_saldo_pedido(p_pedido_id bigint,p_monto numeric,p_sesion_caja_id bigint,p_idempotencia text,p_monto_nuevo numeric default 0,p_metodo public.metodo_pago default 'EFECTIVO')
returns jsonb language plpgsql set search_path=pg_catalog,public as $$
 declare cid bigint; previo public.saldo_cliente_uso%rowtype; uso public.saldo_cliente_uso%rowtype; cobro jsonb; intento jsonb;
begin
 if p_monto is null or p_monto<=0 or p_monto_nuevo is null or p_monto_nuevo<0 or p_monto::text in ('NaN','Infinity','-Infinity') or p_monto_nuevo::text in ('NaN','Infinity','-Infinity') then raise exception 'Importes inválidos';end if;
 if p_idempotencia is null or length(btrim(p_idempotencia))<1 or length(p_idempotencia)>180 then raise exception 'Clave de operación inválida';end if;
 select cliente_id into cid from public.pedido where id=p_pedido_id;
 intento:=jsonb_build_object('pedido',p_pedido_id,'sesion',p_sesion_caja_id,'monto',round(p_monto,2),'nuevo',round(p_monto_nuevo,2),'metodo',p_metodo);
 perform pg_advisory_xact_lock(hashtextextended('saldo-pedido:'||p_idempotencia,0));
 select * into previo from public.saldo_cliente_uso where idempotencia_clave=p_idempotencia;
 if found then
  if previo.solicitud<>intento or previo.anulado_en is not null then raise exception 'Esta clave ya corresponde a otra operación o está anulada';end if;
  return jsonb_build_object('usoId',previo.id,'saldoAplicado',previo.monto,'saldoRestante',greatest(-previo.saldo_despues,0),'reintento',true);
 end if;
 if p_monto+p_monto_nuevo>(public.consultar_saldo_disponible(cid,p_pedido_id)->>'pedidoPendiente')::numeric then raise exception 'El saldo y el dinero nuevo superan el pendiente del pedido';end if;
 insert into public.saldo_cliente_uso(cliente_id,hermes_cliente_id,pedido_id,sesion_caja_id,monto,saldo_antes,saldo_despues,idempotencia_clave,solicitud,creado_por)
 values(cid,0,p_pedido_id,p_sesion_caja_id,p_monto,0,0,p_idempotencia,intento,'') returning * into uso;
 if p_monto_nuevo>0 then
  cobro:=public.registrar_cobro_cation(p_pedido_id=>p_pedido_id,p_monto=>p_monto_nuevo,p_metodo=>p_metodo,p_sesion_id=>p_sesion_caja_id,p_idempotencia=>p_idempotencia||':nuevo');
 end if;
 return jsonb_build_object('usoId',uso.id,'saldoAplicado',uso.monto,'saldoRestante',greatest(-uso.saldo_despues,0),'cobro',cobro,'reintento',false);
end $$;
revoke all on function public.aplicar_saldo_pedido(bigint,numeric,bigint,text,numeric,public.metodo_pago) from public,anon;
grant execute on function public.aplicar_saldo_pedido(bigint,numeric,bigint,text,numeric,public.metodo_pago) to authenticated;

create function hermes.revertir_saldo_venta() returns trigger language plpgsql security definer set search_path=pg_catalog,public,hermes as $$
declare u public.saldo_cliente_uso%rowtype; mid bigint;
begin
 select * into u from public.saldo_cliente_uso where venta_id=new.id and anulado_en is null;
 if not found then return new;end if;
 if not exists(select 1 from public.venta_evento where venta_id=new.id and accion='ANULADA') then raise exception 'Anula la venta mediante la operación oficial para devolver caja, stock y saldo juntos';end if;
 perform 1 from hermes.cliente where id=u.hermes_cliente_id for update;
 insert into hermes.movimiento_cuenta(cliente_id,tipo,monto,idempotencia_clave,fecha_efectiva,referencia,motivo,creado_por)
 values(u.hermes_cliente_id,'AJUSTE',-u.monto,'saldo-reversion-venta-'||new.id,(now() at time zone 'America/La_Paz')::date,new.numero,'Saldo devuelto por anulación de venta',coalesce(new.creado_por,'sistema')) returning id into mid;
 update public.saldo_cliente_uso set anulado_en=now(),motivo_anulacion='Venta anulada',reversion_id=mid where id=u.id;
 return new;
end $$;
revoke all on function hermes.revertir_saldo_venta() from public,anon,authenticated,service_role;
create trigger saldo_revertir_venta after update of estado on public.venta for each row when (new.estado::text='ANULADA' and old.estado is distinct from new.estado) execute function hermes.revertir_saldo_venta();

create function hermes.revertir_saldo_pedido() returns trigger language plpgsql security definer set search_path=pg_catalog,public,hermes as $$
declare cid bigint;r record;
begin
 if not exists(select 1 from public.saldo_cliente_uso where pedido_id=new.id and anulado_en is null) then return new;end if;
 if not public.app_es_admin() then raise exception 'Solo gerencia puede anular un pedido con saldo aplicado' using errcode='42501';end if;
 select id into cid from hermes.cliente where pos_cliente_id=new.cliente_id for update;
 perform 1 from hermes.partida_abierta where cliente_id=cid order by id for update;
 if exists(select 1 from hermes.pago_aplicacion a join hermes.pago p on p.id=a.pago_id join hermes.partida_abierta pa on pa.id=a.partida_id where pa.pedido_id=new.id and p.estado::text in ('CONFIRMADO','ACREDITADO')) then raise exception 'El pedido tiene pagos confirmados: revisa su reversión antes de anular';end if;
 if exists(select 1 from hermes.pago_aplicacion a join hermes.pago p on p.id=a.pago_id join hermes.partida_abierta pa on pa.id=a.partida_id where pa.pedido_id=new.id and p.estado::text='PROPUESTO') then raise exception 'El pedido tiene pagos por verificar: resuélvelos antes de anular';end if;
 update public.saldo_cliente_uso set anulado_en=now(),motivo_anulacion='Pedido anulado' where pedido_id=new.id and anulado_en is null;
 for r in select id,total,documento_interno from hermes.partida_abierta where pedido_id=new.id and estado::text in ('ABIERTA','PAGADA') order by id loop
  update hermes.partida_abierta set estado='ANULADA',anulada_en=now(),anulada_por=auth.uid()::text,motivo_anulacion='Pedido anulado; saldo aplicado restaurado' where id=r.id;
  insert into hermes.movimiento_cuenta(cliente_id,partida_id,tipo,monto,idempotencia_clave,fecha_efectiva,referencia,motivo,creado_por)
   values(cid,r.id,'NOTA_CREDITO',-r.total,'anulacion-partida-'||r.id,(now() at time zone 'America/La_Paz')::date,r.documento_interno,'Pedido anulado; saldo aplicado restaurado',auth.uid()::text);
 end loop;
 return new;
end $$;
revoke all on function hermes.revertir_saldo_pedido() from public,anon,authenticated,service_role;
create trigger saldo_revertir_pedido after update of estado on public.pedido for each row when(new.estado::text='CANCELADO' and old.estado is distinct from new.estado) execute function hermes.revertir_saldo_pedido();

create function hermes.proteger_saldo_venta() returns trigger language plpgsql security definer set search_path=pg_catalog,public as $$
begin
 if pg_trigger_depth()=1 and (new.cliente_acreedor is distinct from old.cliente_acreedor or new.saldo_cliente_antes is distinct from old.saldo_cliente_antes or new.saldo_favor_aplicado is distinct from old.saldo_favor_aplicado) then raise exception 'El estado y consumo de saldo se calculan en la operación de venta';end if;
 if new.estado::text='COMPLETADA' and new.numero like 'VTA-%' and new.saldo_favor_aplicado>0 and
  coalesce((select sum(monto) from public.venta_pago where venta_id=new.id),0)+coalesce((select sum(monto) from public.saldo_cliente_uso where venta_id=new.id and anulado_en is null),0)<>new.total then raise exception 'La venta no está cubierta por saldo y dinero nuevo';end if;
 return new;
end $$;
revoke all on function hermes.proteger_saldo_venta() from public,anon,authenticated,service_role;
create trigger saldo_proteger_venta before update on public.venta for each row execute function hermes.proteger_saldo_venta();

CREATE OR REPLACE FUNCTION public._registrar_venta_nucleo(p_lineas jsonb, p_pagos jsonb, p_sesion_caja_id bigint, p_cliente_id bigint, p_descuento_total numeric, p_usuario text, p_idempotencia text, p_forzar_reserva boolean, p_motivo_forzado text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SET search_path TO pg_catalog, public
AS $function$
declare
  v_venta_id bigint; v_header_ubic bigint; v_linea jsonb;
  v_prod bigint; v_cant numeric; v_cant_pres numeric; v_factor numeric;
  v_unit numeric; v_lista numeric; v_pres bigint; v_pres_base bigint;
  v_forzada bigint; v_st_forzada numeric; v_st_tienda numeric; v_st_almacen numeric;
  v_suc bigint; v_nombre_suc text; v_restante numeric; v_toma numeric;
  v_primer_kid bigint; v_kid bigint; v_ub record;
  v_sub numeric; v_subtotal numeric := 0; v_total numeric; v_pagado numeric; v_pago jsonb;
  v_previa jsonb;
  v_libre boolean; v_ubic_sobregiro bigint;
  v_ix int := 0;
  v_vendible numeric; v_reserva_motivo text; v_exceso numeric;
  v_reservado numeric; -- fix 2026-09-27: LIBRE sin reserva no se bloquea
  -- Brief Caja-1: numeración propia VTA-2026-NNNNN (A1) y recibido/estado de
  -- verificación por pago (A2/A3).
  v_numero text; v_anio int;
  v_metodo metodo_pago; v_recibido numeric; v_estado_verif text;
begin
  if jsonb_typeof(p_lineas) <> 'array' or jsonb_array_length(p_lineas) = 0 then
    raise exception 'p_lineas debe ser un array no vacío';
  end if;
  if jsonb_typeof(p_pagos) <> 'array' or jsonb_array_length(p_pagos) = 0 then
    raise exception 'p_pagos debe ser un array no vacío';
  end if;

  if p_forzar_reserva and (p_motivo_forzado is null or btrim(p_motivo_forzado) = '') then
    raise exception 'El motivo es obligatorio para vender por encima de la reserva';
  end if;

  if p_idempotencia is not null then
    if btrim(p_idempotencia) = '' or length(p_idempotencia) > 200 then
      raise exception 'Clave de idempotencia inválida (vacía, en blanco, o mayor a 200 caracteres)';
    end if;
    perform pg_advisory_xact_lock(hashtextextended('venta:' || p_idempotencia, 0));
    select jsonb_build_object('venta_id', v.id, 'numero', v.numero, 'subtotal', v.subtotal,
             'descuento_total', v.descuento_total, 'total', v.total, 'reintento', true)
      into v_previa
      from venta v
     where v.idempotencia_clave = p_idempotencia;
    if v_previa is not null then
      if exists(select 1 from public.saldo_cliente_uso u where u.venta_id=(v_previa->>'venta_id')::bigint and
          (u.anulado_en is not null or u.solicitud<>jsonb_build_object('lineas',p_lineas,'pagos',p_pagos,'cliente',p_cliente_id,'sesion',p_sesion_caja_id,'descuento',coalesce(p_descuento_total,0)))) then
        raise exception 'La clave corresponde a una venta con datos distintos o anulada';
      end if;
      return v_previa;
    end if;
  end if;

  perform 1 from sesion_caja where id = p_sesion_caja_id and estado = 'ABIERTA';
  if not found then raise exception 'No hay una sesión de caja abierta (%).', p_sesion_caja_id; end if;

  select id into v_header_ubic from ubicacion where sucursal_id = 2 order by id limit 1;
  if v_header_ubic is null then select id into v_header_ubic from ubicacion order by id limit 1; end if;

  -- A1: numeración gap-free — se asigna en la MISMA transacción que la venta, así
  -- que un rollback más abajo (stock insuficiente, pago que no cuadra, etc.) también
  -- revierte el incremento del contador. Mismo patrón que abrir_venta (serie VTD).
  v_anio := extract(year from now() at time zone 'America/La_Paz')::int;
  v_numero := formato_numero('VTA', v_anio, siguiente_numero('VTA', v_anio));

  insert into venta (numero, cliente_id, ubicacion_id, estado, creado_por, sesion_caja_id, idempotencia_clave)
  values (v_numero, p_cliente_id, v_header_ubic, 'ABIERTA', p_usuario, p_sesion_caja_id, p_idempotencia)
  returning id into v_venta_id;

  for v_linea in select * from jsonb_array_elements(p_lineas) loop
    v_ix := v_ix + 1;

    -- 2026-09-29 (personalizados en venta): línea sin producto de catálogo. No toca
    -- stock ni kardex, no tiene presentación; solo suma al total de la venta.
    if coalesce((v_linea->>'es_personalizado')::boolean, false) then
      if nullif(btrim(v_linea->>'producto_id'), '') is not null then
        raise exception 'Una línea personalizada no puede traer producto_id';
      end if;
      if nullif(btrim(v_linea->>'descripcion'), '') is null then
        raise exception 'Línea personalizada sin descripción';
      end if;
      v_unit  := (v_linea->>'precio_unitario')::numeric;
      v_lista := coalesce((v_linea->>'precio_lista')::numeric, v_unit);
      v_cant  := coalesce((v_linea->>'cantidad_base')::numeric, (v_linea->>'cantidad')::numeric);
      if v_unit is null or v_unit <= 0 then
        raise exception 'La línea personalizada "%" no tiene precio', btrim(v_linea->>'descripcion');
      end if;
      if v_cant is null or v_cant <= 0 then raise exception 'cantidad debe ser positiva'; end if;
      insert into venta_linea (venta_id, producto_id, es_personalizado, descripcion, unidad_medida,
                               cantidad, cantidad_presentacion, precio_lista, precio_unitario)
      values (v_venta_id, null, true, btrim(v_linea->>'descripcion'),
              coalesce(nullif(upper(btrim(v_linea->>'unidad_medida')), ''), 'UNIDAD'),
              v_cant, v_cant, v_lista, v_unit);
      v_subtotal := v_subtotal + round(v_unit * v_cant, 2);
      continue;
    end if;

    v_prod  := (v_linea->>'producto_id')::bigint;
    v_unit  := (v_linea->>'precio_unitario')::numeric;
    v_lista := coalesce((v_linea->>'precio_lista')::numeric, v_unit);
    v_pres  := (v_linea->>'presentacion_id')::bigint;
    if v_prod is null or v_unit is null then
      raise exception 'Línea inválida (producto_id/precio_unitario)';
    end if;

    select id into v_pres_base from presentacion
     where producto_id = v_prod and es_base = true and coalesce(activo, true) = true limit 1;
    if v_pres_base is null then raise exception 'Producto % sin presentación base', v_prod; end if;

    if v_pres is not null then
      select factor_unidad_base into v_factor from presentacion
       where id = v_pres and producto_id = v_prod and coalesce(activo, true);
      if v_factor is null then
        raise exception 'La presentación % no pertenece al producto % (o está inactiva)', v_pres, v_prod;
      end if;
      v_cant_pres := (v_linea->>'cantidad_presentacion')::numeric;
      if v_cant_pres is null or v_cant_pres <= 0 then
        raise exception 'cantidad_presentacion debe ser positiva';
      end if;
      v_cant := v_cant_pres * v_factor;
    else
      v_pres := v_pres_base;
      v_cant := coalesce((v_linea->>'cantidad_base')::numeric, (v_linea->>'cantidad')::numeric);
      v_cant_pres := v_cant;
    end if;
    if v_cant is null or v_cant <= 0 then raise exception 'cantidad debe ser positiva'; end if;

    -- ── COMPUERTA 1: origen forzado por el POS ───────────────────────────────
    v_forzada := (v_linea->>'sucursal_origen_id')::bigint;
    if v_forzada is not null then
      v_libre := coalesce(permite_sobregiro_sucursal(v_prod, v_forzada), false);
      select coalesce(sum(sa.cantidad_base), 0) into v_st_forzada
        from stock_actual sa join ubicacion u on u.id = sa.ubicacion_id
       where sa.producto_id = v_prod and u.sucursal_id = v_forzada;
      if v_st_forzada < v_cant and not v_libre then
        select nombre into v_nombre_suc from sucursal where id = v_forzada;
        raise exception 'Stock insuficiente en % para el producto % (necesita %, hay %)',
          coalesce(v_nombre_suc, 'sucursal ' || v_forzada), v_prod, v_cant, v_st_forzada;
      end if;
      v_suc := v_forzada;
    else
      -- ── COMPUERTA 2: elección automática de sucursal ───────────────────────
      select coalesce(sum(sa.cantidad_base), 0) into v_st_tienda
        from stock_actual sa join ubicacion u on u.id = sa.ubicacion_id
       where sa.producto_id = v_prod and u.sucursal_id = 2;
      select coalesce(sum(sa.cantidad_base), 0) into v_st_almacen
        from stock_actual sa join ubicacion u on u.id = sa.ubicacion_id
       where sa.producto_id = v_prod and u.sucursal_id = 1;
      if v_st_tienda >= v_cant then v_suc := 2;
      elsif v_st_almacen >= v_cant then v_suc := 1;
      elsif coalesce(permite_sobregiro_sucursal(v_prod, 2), false) then
        v_suc := 2;
      else
        raise exception 'Stock insuficiente para producto % (necesita %, Tienda %, Almacén %)',
          v_prod, v_cant, v_st_tienda, v_st_almacen;
      end if;
      v_libre := coalesce(permite_sobregiro_sucursal(v_prod, v_suc), false);
    end if;

    -- ── COMPUERTA 2.5: protección de reservas ────────────────────────────────
    select vendible, reservado, motivo into v_vendible, v_reservado, v_reserva_motivo
      from saldo_vendible(array[v_prod], v_suc)
     limit 1;

    -- Fix 2026-09-27: en una sucursal LIBRE (Tienda en venta libre) sin stock contado,
    -- vendible = 0 aunque no haya NINGUNA reserva, y la compuerta bloqueaba toda venta
    -- con "está reservado" falso. Regla S10 intacta: si hay reserva real (reservado > 0),
    -- la reserva sigue ganando sobre LIBRE. Sin reserva, LIBRE vende.
    if v_cant > coalesce(v_vendible, 0)
       and not (coalesce(v_libre, false) and coalesce(v_reservado, 0) = 0) then
      v_exceso := v_cant - coalesce(v_vendible, 0);
      if not p_forzar_reserva then
        raise exception 'Producto % está reservado: % unidad(es) comprometidas para % en esta sucursal (vendible real: %)',
          v_prod, v_exceso, coalesce(v_reserva_motivo, 'otro pedido'), coalesce(v_vendible, 0)
          using errcode = 'check_violation';
      else
        insert into venta_sobre_reserva (venta_id, producto_id, cantidad_base, pedidos_afectados, motivo, usuario)
        values (v_venta_id, v_prod, v_exceso, v_reserva_motivo, p_motivo_forzado, p_usuario);
      end if;
    end if;

    -- ── COMPUERTA 3: reparto entre ubicaciones ───────────────────────────────
    v_restante := v_cant; v_primer_kid := null;
    for v_ub in
      select sa.ubicacion_id, sa.cantidad_base
        from stock_actual sa join ubicacion u on u.id = sa.ubicacion_id
       where sa.producto_id = v_prod and u.sucursal_id = v_suc and sa.cantidad_base > 0
       order by sa.cantidad_base desc
    loop
      exit when v_restante <= 0;
      v_toma := least(v_restante, v_ub.cantidad_base);
      v_kid := registrar_salida(v_pres_base, v_ub.ubicacion_id, v_toma,
        'Venta #' || v_venta_id, p_usuario, current_date,
        'venta:' || v_venta_id || ':l' || v_ix || ':p' || v_prod || ':u' || v_ub.ubicacion_id, false);
      if v_primer_kid is null then v_primer_kid := v_kid; end if;
      v_restante := v_restante - v_toma;
    end loop;

    if v_restante > 0 then
      if not v_libre then
        raise exception 'Stock insuficiente (carrera) producto %', v_prod;
      end if;
      select sa.ubicacion_id into v_ubic_sobregiro
        from stock_actual sa join ubicacion u on u.id = sa.ubicacion_id
       where sa.producto_id = v_prod and u.sucursal_id = v_suc
       order by sa.cantidad_base desc limit 1;
      if v_ubic_sobregiro is null then
        select id into v_ubic_sobregiro from ubicacion
         where sucursal_id = v_suc order by id limit 1;
      end if;
      if v_ubic_sobregiro is null then
        raise exception 'La sucursal % no tiene ninguna ubicación configurada', v_suc;
      end if;

      v_kid := registrar_salida(v_pres_base, v_ubic_sobregiro, v_restante,
        'Venta #' || v_venta_id, p_usuario, current_date,
        'venta:' || v_venta_id || ':l' || v_ix || ':p' || v_prod || ':sobregiro', true);
      if v_primer_kid is null then v_primer_kid := v_kid; end if;
      v_restante := 0;
    end if;

    v_sub := round(v_unit * v_cant_pres, 2);
    insert into venta_linea (venta_id, producto_id, presentacion_id, cantidad,
                             cantidad_presentacion, precio_lista, precio_unitario,
                             kardex_transaccion_id)
    values (v_venta_id, v_prod, v_pres, v_cant, v_cant_pres, v_lista, v_unit, v_primer_kid);
    v_subtotal := v_subtotal + v_sub;
  end loop;

  v_total := round(v_subtotal - coalesce(p_descuento_total, 0), 2);
  select coalesce(sum((p->>'monto')::numeric), 0) into v_pagado from jsonb_array_elements(p_pagos) p;
  if round(v_pagado, 2) <> v_total then
    raise exception 'El pago (%) no coincide con el total (%)', v_pagado, v_total;
  end if;
  if v_total<=0 or exists(select 1 from jsonb_array_elements(p_pagos) p where (p->>'monto') is null or (p->>'monto')::numeric<=0 or (p->>'monto')::numeric::text in ('NaN','Infinity','-Infinity')) then
    raise exception 'El total y los pagos deben ser positivos';
  end if;
  if (select count(*) from jsonb_array_elements(p_pagos) p where p->>'metodo'='SALDO_FAVOR')>1 then raise exception 'Solo se admite una aplicación de saldo por venta';end if;
  update public.venta set subtotal=v_subtotal,total=v_total,descuento_total=coalesce(p_descuento_total,0) where id=v_venta_id;
  for v_pago in select * from jsonb_array_elements(p_pagos) loop
    if v_pago->>'metodo'='SALDO_FAVOR' then
      insert into public.saldo_cliente_uso(cliente_id,hermes_cliente_id,venta_id,sesion_caja_id,monto,saldo_antes,saldo_despues,idempotencia_clave,solicitud,creado_por)
      values(p_cliente_id,0,v_venta_id,p_sesion_caja_id,(v_pago->>'monto')::numeric,0,0,'saldo-venta:'||v_venta_id,
        jsonb_build_object('lineas',p_lineas,'pagos',p_pagos,'cliente',p_cliente_id,'sesion',p_sesion_caja_id,'descuento',coalesce(p_descuento_total,0)),'');
      continue;
    end if;
    v_metodo := (v_pago->>'metodo')::metodo_pago;

    -- A2: "recibido" (solo tiene sentido en EFECTIVO, pero se valida siempre que
    -- venga) nunca entra en la suma de p_pagos — el chequeo de arriba ya corrió.
    v_recibido := (v_pago->>'recibido')::numeric;
    if v_recibido is not null and v_recibido < (v_pago->>'monto')::numeric then
      raise exception 'El monto recibido (%) no puede ser menor al monto del pago (%)', v_recibido, (v_pago->>'monto')::numeric;
    end if;

    -- A3: QR/TRANSFERENCIA quedan PENDIENTE de verificación (Caja-2 los concilia);
    -- EFECTIVO (y cualquier otro método que llegue por acá) no aplica.
    v_estado_verif := case when v_metodo in ('QR', 'TRANSFERENCIA') then 'PENDIENTE' else 'NO_APLICA' end;

    insert into venta_pago (venta_id, metodo, monto, recibido, referencia, estado_verificacion)
    values (v_venta_id, v_metodo, (v_pago->>'monto')::numeric, v_recibido, v_pago->>'referencia', v_estado_verif);
    insert into movimiento_caja (sesion_caja_id, tipo, metodo, monto, venta_id, creado_por)
    values (p_sesion_caja_id, 'VENTA', v_metodo, (v_pago->>'monto')::numeric, v_venta_id, p_usuario);
  end loop;
  update venta set subtotal = v_subtotal, descuento_total = coalesce(p_descuento_total, 0),
                   total = v_total, estado = 'COMPLETADA', completado_en = now()
   where id = v_venta_id;
  return jsonb_build_object('venta_id', v_venta_id, 'numero', v_numero, 'subtotal', v_subtotal,
                            'descuento_total', coalesce(p_descuento_total, 0), 'total', v_total);
end;
