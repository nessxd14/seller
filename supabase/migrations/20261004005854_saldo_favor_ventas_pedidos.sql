create or replace view hermes.v_partida_estado with(security_invoker=true) as  SELECT pa.id AS partida_id,
    pa.cliente_id,
    pa.pedido_id,
    pa.referencia,
    pa.documento_interno,
    pa.estado,
    pa.total,
    pa.creado_en,
    pa.fecha_entrega,
    pa.plazo_dias,
    (COALESCE(ap.imputado, 0::numeric) + COALESCE(sf.aplicado, 0::numeric)) AS imputado,
    pa.total - (COALESCE(ap.imputado, 0::numeric) + COALESCE(sf.aplicado, 0::numeric)) AS pendiente,
    COALESCE(rev.en_revision, 0::numeric) AS en_revision,
    ( SELECT count(*) AS count
           FROM hermes.hito h
          WHERE h.partida_abierta_id = pa.id AND h.obligatorio) AS hitos_obligatorios,
    ( SELECT count(*) AS count
           FROM hermes.hito h
          WHERE h.partida_abierta_id = pa.id AND h.obligatorio AND h.estado = 'COMPLETO'::hermes.estado_hito) AS hitos_cumplidos,
    ( SELECT h.nombre
           FROM hermes.hito h
          WHERE h.partida_abierta_id = pa.id AND h.obligatorio AND h.estado <> 'COMPLETO'::hermes.estado_hito
          ORDER BY h.orden
         LIMIT 1) AS proximo_hito,
    CURRENT_DATE - (pa.creado_en AT TIME ZONE 'America/La_Paz'::text)::date AS dias_abierta
   FROM hermes.partida_abierta pa
     LEFT JOIN (SELECT a.partida_id,sum(a.monto) aplicado FROM hermes.saldo_uso_partida a
       JOIN public.saldo_cliente_uso u ON u.id=a.uso_id WHERE u.anulado_en IS NULL GROUP BY a.partida_id) sf ON sf.partida_id=pa.id
     LEFT JOIN ( SELECT ap_1.partida_id,
            sum(ap_1.monto) AS imputado
           FROM hermes.pago_aplicacion ap_1
             JOIN hermes.pago p ON p.id = ap_1.pago_id
          WHERE p.estado = ANY (ARRAY['CONFIRMADO'::hermes.estado_pago, 'ACREDITADO'::hermes.estado_pago])
          GROUP BY ap_1.partida_id) ap ON ap.partida_id = pa.id
     LEFT JOIN ( SELECT ap_1.partida_id,
            sum(ap_1.monto) AS en_revision
           FROM hermes.pago_aplicacion ap_1
             JOIN hermes.pago p ON p.id = ap_1.pago_id
          WHERE p.estado = 'PROPUESTO'::hermes.estado_pago
          GROUP BY ap_1.partida_id) rev ON rev.partida_id = pa.id;;

create or replace view hermes.v_anticipo_cliente with(security_invoker=true) as  SELECT p.id AS pago_id,
    p.cliente_id,
    p.monto,
    (COALESCE(ap.imputado, 0::numeric) + COALESCE(sf.aplicado,0::numeric)) AS imputado,
    p.monto - (COALESCE(ap.imputado, 0::numeric) + COALESCE(sf.aplicado,0::numeric)) AS saldo_favor,
    p.no_imputar,
    p.medio,
    p.estado,
    p.referencia,
    p.fecha_recepcion,
    p.fecha_acreditacion,
    p.confirmado_en,
    p.evidencia_id,
    e.storage_path AS comprobante_path,
    e.nombre_original AS comprobante_nombre,
    p.evidencia_id IS NOT NULL AS tiene_comprobante
   FROM hermes.pago p
     LEFT JOIN (SELECT m.pago_id,sum(f.monto) aplicado FROM hermes.saldo_uso_fuente f
       JOIN public.saldo_cliente_uso u ON u.id=f.uso_id JOIN hermes.movimiento_cuenta m ON m.id=f.movimiento_id
       WHERE u.anulado_en IS NULL AND m.pago_id IS NOT NULL GROUP BY m.pago_id) sf ON sf.pago_id=p.id
     LEFT JOIN hermes.evidencia e ON e.id = p.evidencia_id
     LEFT JOIN ( SELECT ap_1.pago_id,
            sum(ap_1.monto) AS imputado
           FROM hermes.pago_aplicacion ap_1
          GROUP BY ap_1.pago_id) ap ON ap.pago_id = p.id
  WHERE (p.estado = ANY (ARRAY['CONFIRMADO'::hermes.estado_pago, 'ACREDITADO'::hermes.estado_pago])) AND (p.monto - (COALESCE(ap.imputado, 0::numeric) + COALESCE(sf.aplicado,0::numeric))) > 0::numeric;;

CREATE OR REPLACE FUNCTION public.resumen_turno(p_sesion_id bigint)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_rol text;
  v_ses sesion_caja%rowtype;
  v_ventas jsonb; v_ventas_retail jsonb; v_ventas_vtd jsonb;
  v_anticipos jsonb; v_anulaciones jsonb; v_gastos jsonb;
  v_remesas numeric; v_inyecciones numeric; v_cantidad_ventas int; v_cantidad_vtd int;
  v_pendientes int; v_esperado numeric; v_neto numeric; v_rechazados jsonb;
  v_vtd_pend jsonb;
begin
  v_rol := app_rol_actual();
  if v_rol is null then raise exception 'No autorizado'; end if;

  select * into v_ses from sesion_caja where id = p_sesion_id;
  if not found then raise exception 'Sesión % no existe', p_sesion_id; end if;

  if v_rol = 'cajero' and v_ses.cajero_id is distinct from auth.uid() then
    raise exception 'Solo podés ver tu propio turno';
  elsif v_rol not in ('cajero', 'gerente', 'admin') then
    raise exception 'No autorizado';
  end if;

  select coalesce(jsonb_object_agg(metodo, monto), '{}'::jsonb) into v_ventas
    from (select metodo::text as metodo, sum(monto) as monto from movimiento_caja
           where sesion_caja_id = p_sesion_id and tipo = 'VENTA' group by metodo) t;

  select coalesce(jsonb_object_agg(metodo, monto), '{}'::jsonb) into v_ventas_retail
    from (select m.metodo::text as metodo, sum(m.monto) as monto
            from movimiento_caja m left join venta v on v.id = m.venta_id
           where m.sesion_caja_id = p_sesion_id and m.tipo = 'VENTA'
             and coalesce(v.numero, '') not like 'VTD-%'
           group by m.metodo) t;

  select coalesce(jsonb_object_agg(metodo, monto), '{}'::jsonb) into v_ventas_vtd
    from (select m.metodo::text as metodo, sum(m.monto) as monto
            from movimiento_caja m join venta v on v.id = m.venta_id
           where m.sesion_caja_id = p_sesion_id and m.tipo = 'VENTA'
             and v.numero like 'VTD-%'
           group by m.metodo) t;

  select coalesce(jsonb_object_agg(metodo, monto), '{}'::jsonb) into v_anticipos
    from (select metodo::text as metodo, sum(monto) as monto from movimiento_caja
           where sesion_caja_id = p_sesion_id and tipo = 'ANTICIPO' and not fuera_de_arqueo group by metodo) t;

  select coalesce(jsonb_object_agg(metodo, monto), '{}'::jsonb) into v_anulaciones
    from (select metodo::text as metodo, sum(monto) as monto from movimiento_caja
           where sesion_caja_id = p_sesion_id and tipo = 'ANULACION' group by metodo) t;

  select coalesce(jsonb_object_agg(lower(estado), monto), '{}'::jsonb) into v_gastos
    from (select g.estado, sum(g.monto) as monto from caja_gasto g
           where g.sesion_caja_id = p_sesion_id group by g.estado) t;

  select coalesce(sum(monto), 0) into v_remesas from movimiento_caja
   where sesion_caja_id = p_sesion_id and subtipo = 'REMESA';
  select coalesce(sum(monto), 0) into v_inyecciones from movimiento_caja
   where sesion_caja_id = p_sesion_id and subtipo = 'INYECCION';

  select count(*) into v_cantidad_ventas from venta
   where sesion_caja_id = p_sesion_id and estado = 'COMPLETADA'
     and coalesce(numero, '') not like 'VTD-%';

  select count(distinct m.venta_id) into v_cantidad_vtd
    from movimiento_caja m join venta v on v.id = m.venta_id
   where m.sesion_caja_id = p_sesion_id and m.tipo = 'VENTA' and v.numero like 'VTD-%';

  select jsonb_build_object('cantidad', count(*), 'total', coalesce(sum(total), 0))
    into v_vtd_pend
    from v_vtd_por_cobrar;

  select count(*) into v_pendientes from venta_pago vp
    join venta v on v.id = vp.venta_id
   where vp.estado_verificacion = 'PENDIENTE'
     and exists (select 1 from movimiento_caja m
                  where m.venta_id = v.id and m.sesion_caja_id = p_sesion_id and m.tipo = 'VENTA');

  select coalesce(jsonb_agg(jsonb_build_object('venta_id', v.id, 'numero', v.numero, 'metodo', vp.metodo, 'monto', vp.monto)), '[]'::jsonb)
    into v_rechazados
    from venta_pago vp join venta v on v.id = vp.venta_id
   where vp.estado_verificacion = 'RECHAZADO'
     and exists (select 1 from movimiento_caja m
                  where m.venta_id = v.id and m.sesion_caja_id = p_sesion_id and m.tipo = 'VENTA');

  if v_rol in ('gerente', 'admin') then
    select coalesce(sum(case when tipo in ('VENTA', 'ANTICIPO', 'INGRESO') then monto
                             when tipo in ('EGRESO', 'ANULACION') then -monto else 0 end), 0)
      into v_neto
    from movimiento_caja where sesion_caja_id = p_sesion_id and metodo = 'EFECTIVO' and not fuera_de_arqueo;
    v_esperado := v_ses.monto_apertura + v_neto;
  else
    v_esperado := null;
  end if;

  return jsonb_build_object(
    'apertura', v_ses.monto_apertura,
    'saldo_favor_aplicado',(select coalesce(sum(monto),0) from public.saldo_cliente_uso where sesion_caja_id=p_sesion_id and anulado_en is null),
    'ventas_total',(select coalesce(sum(total),0) from public.venta where sesion_caja_id=p_sesion_id and estado::text='COMPLETADA' and numero like 'VTA-%'),
    'ventas_acreedores',(select count(*) from public.venta where sesion_caja_id=p_sesion_id and estado::text='COMPLETADA' and cliente_acreedor),
    'ventas', v_ventas,
    'ventas_retail', v_ventas_retail,
    'ventas_vtd', v_ventas_vtd,
    'anticipos', v_anticipos, 'cobros_fuera_arqueo', (select coalesce(sum(monto), 0) from movimiento_caja where sesion_caja_id = p_sesion_id and fuera_de_arqueo),
    'anulaciones', v_anulaciones,
    'gastos', v_gastos,
    'remesas', v_remesas,
    'inyecciones', v_inyecciones,
    'cantidad_ventas', v_cantidad_ventas,
    'cantidad_vtd_cobradas', v_cantidad_vtd,
    'vtd_por_cobrar', v_vtd_pend,
    'pagos_pendientes_verificacion', v_pendientes,
    'pagos_rechazados', v_rechazados,
    'diferencia_relevo', v_ses.diferencia_relevo,
    'esperado_efectivo', v_esperado
  );
end;
$function$
;

CREATE OR REPLACE FUNCTION hermes.anular_partida(p_partida_id bigint, p_motivo text, p_usuario text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'hermes', 'public'
AS $function$
declare
  v_pa       record;
  v_aplicado numeric;
begin
 if not hermes.contexto_confiable() and not public.hermes_tiene_acceso() then
 raise exception 'Sin acceso a Hermes' using errcode='42501'; end if;
  if not contexto_confiable() and rol_actual() <> 'gerente' then
    raise exception 'Solo el rol gerente puede anular una partida';
  end if;
  if p_motivo is null or btrim(p_motivo) = '' then
    raise exception 'El motivo es obligatorio';
  end if;

  select * into v_pa from partida_abierta where id = p_partida_id for update;
  if not found then raise exception 'La partida % no existe', p_partida_id; end if;
  if exists(select 1 from hermes.saldo_uso_partida a join public.saldo_cliente_uso u on u.id=a.uso_id where a.partida_id=p_partida_id and u.anulado_en is null) then
    raise exception 'Esta partida tiene saldo a favor aplicado. Anula el pedido en Seller para restaurarlo de forma conjunta.';
  end if;
  if v_pa.estado <> 'ABIERTA' then
    raise exception 'La partida % está en estado % y no se puede anular', p_partida_id, v_pa.estado;
  end if;

  select coalesce(sum(pap.monto), 0) into v_aplicado
    from pago_aplicacion pap
    join pago pg on pg.id = pap.pago_id
   where pap.partida_id = p_partida_id
     and pg.estado in ('CONFIRMADO', 'ACREDITADO');
  if v_aplicado > 0 then
    raise exception 'La partida % tiene Bs % aplicados: no se puede anular', p_partida_id, v_aplicado;
  end if;

  update partida_abierta
     set estado = 'ANULADA', anulada_en = now(), anulada_por = p_usuario,
         motivo_anulacion = btrim(p_motivo)
   where id = p_partida_id;

  insert into movimiento_cuenta (
    cliente_id, partida_id, tipo, monto, idempotencia_clave,
    fecha_efectiva, referencia, motivo, creado_por
  ) values (
    v_pa.cliente_id, p_partida_id, 'NOTA_CREDITO', -v_pa.total,
    'anulacion-partida-' || p_partida_id, current_date,
    v_pa.documento_interno, 'Anulación: ' || btrim(p_motivo), p_usuario
  );
end;
$function$
;
notify pgrst,'reload schema';
